import re,glob,os
os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src'))
src=''.join(open(f,encoding='utf-8').read() for f in glob.glob('**/*.tsx',recursive=True)+glob.glob('**/*.ts',recursive=True))
c=sorted(set(map(lambda m:tuple(map(int,m)),re.findall(r'--c-(\d+)-(\d+)-(\d+)\)',src))))
h=sorted(set(map(lambda m:tuple(map(int,m)),re.findall(r'--h-(\d+)-(\d+)-(\d+)\)',src))))
w=sorted(set(map(lambda m:tuple(map(int,m)),re.findall(r'--w-(\d+)-(\d+)-(\d+)\)',src))))
def fam(t):
    r,g,b=t
    if t==(255,255,255): return 'ink'
    if t==(0,0,0): return 'inkinv'
    if t in((12,10,9),(20,18,16)): return 'surface'
    if t==(251,191,36): return 'warning'
    if r>=200 and 120<=g<=235 and b<=120: return 'accent'
    if r>=200 and g<=170 and b<=170: return 'danger'
    if g>=150 and r<=170 and b<=170: return 'success'
    if b>=200 and r<=140: return 'info'
    if g>=190 and b>=190 and r<=120: return 'info'
    return None
V={'dark':{'ink':'255 255 255','inkinv':'255 255 255','accent':'123 147 255','danger':'248 113 113','success':'74 222 128','info':'56 189 248','surface':'22 26 33','warning':'251 191 36'},
   'light':{'ink':'15 23 42','inkinv':'0 0 0','accent':'59 91 219','danger':'180 35 24','success':'20 128 74','info':'3 105 161','surface':'255 255 255','warning':'161 98 7'}}
def gold(hh): return 30<=hh<=50
def wmap(t,mode):
    hh,s,l=t
    if s<40 and 20<=hh<=40:
        if l>=70: return '220 24% 94%' if mode=='dark' else '215 25% 11%'
        return '218 11% 62%' if mode=='dark' else '219 11% 40%'
    if gold(hh) and s>=40: return '228 100% 74%' if mode=='dark' else '229 68% 48%'
    if hh in (0,350,355) and s>=40: return '0 91% 71%' if mode=='dark' else '5 74% 40%'
    return None
def hmap(t,mode):
    hh,s,l=t
    if gold(hh): return '228 100% 74%' if mode=='dark' else '229 68% 48%'
    return f'{hh} {s}% {max(l,62)}%' if mode=='dark' else f'{hh} {s}% {min(l,38)}%'
def block(mode):
    out=[]
    for t in c:
        f=fam(t)
        if f: out.append(f'  --c-{t[0]}-{t[1]}-{t[2]}: {V[mode][f]};')
    for t in h: out.append(f'  --h-{t[0]}-{t[1]}-{t[2]}: {hmap(t,mode)};')
    for t in w:
        v=wmap(t,mode)
        if v: out.append(f'  --w-{t[0]}-{t[1]}-{t[2]}: {v};')
    return '\n'.join(out)
fancy='\n'.join([f'  --c-{r}-{g}-{b}: {r} {g} {b};' for r,g,b in c]+[f'  --h-{a}-{b}-{d}: {a} {b}% {d}%;' for a,b,d in h]+[f'  --w-{a}-{b}-{d}: {a} {b}% {d}%;' for a,b,d in w])
css=f'''/* @@color-vars-start (generated by frontend/scripts/gen_color_vars.py — page inline-style colour channels) */
:root {{
{fancy}
  --btn-primary-bg: linear-gradient(180deg, hsl(38, 70%, 50%) 0%, hsl(38, 65%, 42%) 100%);
  --btn-primary-bg-diag: linear-gradient(135deg, hsl(38, 70%, 50%) 0%, hsl(32, 65%, 42%) 100%);
  --btn-primary-text: hsl(220, 6%, 9%);
}}
.ui-default {{
{block('dark')}
  --btn-primary-bg: var(--color-accent);
  --btn-primary-bg-diag: var(--color-accent);
  --btn-primary-text: #0e1116;
}}
.ui-default.light {{
{block('light')}
  --btn-primary-text: #ffffff;
}}
/* @@color-vars-end */'''
p='index.css'
s=open(p,encoding='utf-8').read()
if '@@color-vars-start' in s:
    i=s.index('/* @@color-vars-start'); j=s.index('/* @@color-vars-end */')+len('/* @@color-vars-end */')
    s=s[:i]+css+s[j:]
else:
    # strip earlier ad-hoc blocks
    i=s.index('/* ── Colour channels used by page'); j=s.index('@layer base {')
    s=s[:i]+css+'\n\n'+s[j:]
open(p,'w',encoding='utf-8').write(s)
print(len(c),len(h),len(w))
